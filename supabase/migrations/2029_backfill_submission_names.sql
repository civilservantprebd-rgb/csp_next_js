-- কেন দরকার:
-- `submissions.student_name` সাবমিটের সময় snapshot হিসেবে লেখা হয়। আগে কেউ
-- পোর্টাল থেকে নাম বদলালে শুধু `allowed_students.name` বদলাত, পুরোনো
-- সাবমিশনে পুরোনো নামই থেকে যেত — ফলে লিডারবোর্ডে পুরোনো নাম দেখাত।
--
-- এখন অ্যাপ নিজেই নাম বদলের সময় পুরোনো সাবমিশন হালনাগাদ করে, এবং
-- লিডারবোর্ড সরাসরি রোস্টার থেকেও নাম মেলায়। তবু **এই মাইগ্রেশন চালানোর আগে**
-- যারা নাম বদলেছিলেন, তাঁদের সারিগুলো একবার ঠিক করে নিতে এটি চালান।
--
-- কিছুই মোছা বা বদলানো হয় না — শুধু যেখানে নাম রোস্টারের সাথে মিলছে না,
-- সেখানে রোস্টারের নামটি কপি করা হয়।
-- ============================================================

-- ১. আগে দেখে নিন কত সারি বদলাবে (ঐচ্ছিক — শুধু পড়া)
select count(*) as rows_to_update
  from public.submissions s
  join public.allowed_students a on a.id = s.student_id
 where coalesce(a.name, '') <> ''
   and s.student_name is distinct from a.name;

-- ২. হালনাগাদ
update public.submissions s
   set student_name = a.name
  from public.allowed_students a
 where a.id = s.student_id
   and coalesce(a.name, '') <> ''
   and s.student_name is distinct from a.name;

-- ৩. এরপর ১ নম্বর কুয়েরি আবার চালালে ০ আসা উচিত।

-- লক্ষ্য করুন: এটি শুধু সেসব সাবমিশন ঠিক করে যাদের `student_id` রোস্টারের
-- `id`-এর সাথে হুবহু মেলে (পেইড পরীক্ষা — ফোন-আইডি keyed)। ফ্রি পরীক্ষায়
-- `student_id` হলো Google uid, তাই রোস্টারে ঐ uid-এর রো না থাকলে মিলবে না —
-- সেই ক্ষেত্রে শিক্ষার্থী পোর্টাল থেকে নাম একবার সেভ করলেই ঠিক হয়ে যাবে।
